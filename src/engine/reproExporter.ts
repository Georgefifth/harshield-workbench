import { HarEntry, SanitizationResult } from '../types/har';

function shellEscapeSingleQuote(str: string): string {
  return str.replace(/'/g, `'\\''`);
}

export function generateCurlScript(result: SanitizationResult, selectedIndex?: number): string {
  const entries = result.sanitizedHar.log.entries;
  const targets: Array<{ entry: HarEntry; idx: number }> =
    selectedIndex !== undefined && entries[selectedIndex]
      ? [{ entry: entries[selectedIndex], idx: selectedIndex }]
      : entries.map((entry, idx) => ({ entry, idx }));

  const blocks = targets.map(({ entry, idx }) => {
    const req = entry.request;
    const resp = entry.response;
    const lines: string[] = [
      `# [Entry #${idx + 1}] ${req.method} ${req.url} -> Expected HTTP ${resp.status} ${resp.statusText}`,
      `curl -i -X ${req.method} '${shellEscapeSingleQuote(req.url)}' \\`,
    ];

    req.headers.forEach((h) => {
      lines.push(`  -H '${shellEscapeSingleQuote(`${h.name}: ${h.value}`)}' \\`);
    });

    if (req.postData?.text) {
      const compactBody = req.postData.text.replace(/\n\s*/g, ' ');
      lines.push(`  --data-raw '${shellEscapeSingleQuote(compactBody)}'`);
    } else {
      // strip trailing backslash on last line
      lines[lines.length - 1] = lines[lines.length - 1].replace(/ \\$/, '');
    }

    return lines.join('\n');
  });

  return [
    `#!/usr/bin/env bash`,
    `# Generated by HARshield Workbench (${result.sha256Digest})`,
    `# Zero-Leak Verified: ${result.findings.length} credentials pseudonymized across ${entries.length} HTTP entries`,
    `set -euo pipefail`,
    ``,
    blocks.join('\n\n'),
  ].join('\n');
}

export function generatePlaywrightTest(result: SanitizationResult): string {
  const entries = result.sanitizedHar.log.entries;
  const steps = entries
    .map((entry, idx) => {
      const req = entry.request;
      const resp = entry.response;
      const headersObj: Record<string, string> = {};
      req.headers.forEach((h) => {
        headersObj[h.name] = h.value;
      });
      const methodLower = req.method.toLowerCase();
      const supportedMethod = ['get', 'post', 'put', 'delete', 'patch', 'head'].includes(methodLower)
        ? methodLower
        : 'fetch';

      let dataBlock = '';
      if (req.postData?.text) {
        dataBlock = `,\n      data: ${JSON.stringify(req.postData.text)}`;
      }

      return [
        `  // Step ${idx + 1}: ${req.method} ${req.url} (Recorded status: ${resp.status})`,
        `  const res_${idx + 1} = await request.${supportedMethod}(${JSON.stringify(req.url)}, {`,
        `    headers: ${JSON.stringify(headersObj, null, 6).replace(/\n/g, '\n    ')}${dataBlock}`,
        `  });`,
        `  expect(res_${idx + 1}.status()).toBe(${resp.status});`,
      ].join('\n');
    })
    .join('\n\n');

  return [
    `import { test, expect } from '@playwright/test';`,
    ``,
    `/**`,
    ` * Sanitized Reproduction Spec generated by HARshield Workbench`,
    ` * Integrity Digest: ${result.sha256Digest}`,
    ` * Referential Pseudonyms: ${result.lineageGroups.map((g) => g.pseudonym).join(', ') || 'None'}`,
    ` */`,
    `test('reproduce sanitized HTTP trace (${entries.length} requests)', async ({ request }) => {`,
    steps,
    `});`,
  ].join('\n');
}

export function generateMarkdownReport(result: SanitizationResult, traceTitle: string): string {
  const entries = result.sanitizedHar.log.entries;
  const audit = result.competitorAudit;

  const entryRows = entries
    .map((e, i) => {
      const statusBadge = e.response.status >= 400 ? `**${e.response.status} ${e.response.statusText}**` : `${e.response.status}`;
      return `| #${i + 1} | \`${e.request.method}\` | \`${e.request.url.slice(0, 72)}\` | ${statusBadge} | ${e.time} ms |`;
    })
    .join('\n');

  const lineageRows = result.lineageGroups
    .slice(0, 8)
    .map((g) => {
      const chain = g.occurrences
        .map((o) => `Entry #${o.entryIndex + 1} (${o.direction.toUpperCase()} ${o.status} ${o.role})`)
        .join(' → ');
      return `- **\`${g.pseudonym}\`** (${g.category}): ${chain}`;
    })
    .join('\n');

  return [
    `# Diagnostic Incident Bundle — ${traceTitle}`,
    ``,
    `- **Sanitizer Engine**: HARshield Workbench v1.0 (100% Client-Side AST Engine)`,
    `- **Output Integrity**: \`${result.isJsonValid ? '100% VALID HAR 1.2 JSON' : 'INVALID'}\` · \`${result.remainingRawLeaks} Raw Leaks\` · \`${result.sha256Digest}\``,
    `- **Trace Compression**: ${result.originalHar.log.entries.length} raw entries → ${entries.length} core entries (${result.originalBytes} B → ${result.sanitizedBytes} B)`,
    `- **Competitor Gap Verification**:`,
    `  - Chrome DevTools Header-Only Scrubber missed **${audit.chromeHeaderScrubberMissed}** nested body/query secrets`,
    `  - Cloudflare \`har-sanitizer\` regex missed **${audit.cloudflareRegexMissed}** secrets${audit.cloudflareJsonCorrupted ? ' and **corrupted JSON validity (Issue #22)**' : ''}`,
    `  - HARshield AST Engine caught **${audit.harshieldCaught}/${result.findings.length}** secrets with 100% valid JSON`,
    ``,
    `## 1. Filtered HTTP Request Sequence`,
    ``,
    `| Step | Method | Endpoint | HTTP Status | Latency |`,
    `|---|---|---|---|---|`,
    entryRows,
    ``,
    `## 2. Cross-Request Credential Lineage (Referential Integrity Preserved)`,
    ``,
    lineageRows || '_No multi-hop credentials detected._',
    ``,
    `## 3. Redacted cURL Reproduction`,
    ``,
    '```bash',
    generateCurlScript(result),
    '```',
  ].join('\n');
}
